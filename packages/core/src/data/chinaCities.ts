/** 模糊查询:去掉"市/省/自治区"后缀与空格后精确匹配,再做前缀匹配 */
export function lookupCity(name: string): CityCoord | null {
  const key = name.replace(/[\s市省县区]|自治区|特别行政区/g, '');
  if (CHINA_CITIES[key]) return CHINA_CITIES[key];
  for (const [city, coord] of Object.entries(CHINA_CITIES)) {
    if (key.startsWith(city) || city.startsWith(key)) return coord;
  }
  return null;
}
